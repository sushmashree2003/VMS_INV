    public class PettyCash_AutoRefernceNo_Generation
    {
        public PettyCashContext _db;

        public PettyCash_AutoRefernceNo_Generation(PettyCashContext db)
        {
            _db = db;
        }

        public string GenerateReferenceNo(long MI_Id, long IMFY_Id, string GenTypeFlag)
        {
            string AutoGeneratedNo = "";
            try
            {
                using (var cmd = _db.Database.GetDbConnection().CreateCommand())
                {
                    cmd.CommandText = "PC_AutoGeneration_ReferenceNo";
                    cmd.CommandType = CommandType.StoredProcedure;

                    cmd.Parameters.Add(new SqlParameter("@MI_Id", SqlDbType.VarChar) { Value = MI_Id });
                    cmd.Parameters.Add(new SqlParameter("@IMFY_Id", SqlDbType.VarChar) { Value = IMFY_Id });
                    cmd.Parameters.Add(new SqlParameter("@GenTypeFlag", SqlDbType.VarChar) { Value = GenTypeFlag });
                    cmd.Parameters.Add(new SqlParameter("@AutogenerateNo", SqlDbType.VarChar, Int32.MaxValue) { Direction = ParameterDirection.Output });

                    if (cmd.Connection.State != ConnectionState.Open)
                        cmd.Connection.Open();

                    var data1 = cmd.ExecuteNonQuery();

                    AutoGeneratedNo = cmd.Parameters["@AutogenerateNo"].Value.ToString();
                }
            }
            catch (Exception ex)
            {
                AutoGeneratedNo = "Error";
                Console.WriteLine(ex.Message);
            }

            return AutoGeneratedNo;
        }
        public string GetEmailIdForPettyCash(long MI_Id, string SMA_HeaderName, string SMA_SMSMailCallFlag)
        {
            string Emailid = "";
            try
            {
                var approvaldetails = _db.SMSMasterApprovalDMO.Where(t => t.MI_Id == MI_Id && t.SMA_ActiveFlag == true && t.SMA_HeaderName.Trim().ToLower() == SMA_HeaderName.ToLower() && t.SMA_SMSMailCallFlag == SMA_SMSMailCallFlag).Distinct().OrderBy(t => t.SMA_Level).ToList();

                if (approvaldetails.Count > 0)
                {
                    var getuserid = approvaldetails.FirstOrDefault().IVRMUL_Id;

                    var getempcode = _db.Staff_User_Login.Where(a => a.Id == getuserid).ToList();

                    var getemailids = (from a in _db.MasterEmployee
                                       from b in _db.Multiple_Email_DMO
                                       where (a.HRME_Id == b.HRME_Id && b.HRMEM_DeFaultFlag.ToLower() == "default"
                                       && a.HRME_Id == getempcode.FirstOrDefault().Emp_Code
                                       && b.HRME_Id == getempcode.FirstOrDefault().Emp_Code)
                                       select new PC_RequisitionDTO
                                       {
                                           emailids = b.HRMEM_EmailId
                                       }).Distinct().ToList();

                    if (getemailids.Count > 0)
                    {
                        Emailid = getemailids.FirstOrDefault().emailids;
                    }
                }
            }
            catch(Exception ex)
            {
                Console.WriteLine(ex.Message);
            }
            return Emailid;
        }
    }
