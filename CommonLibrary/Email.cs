        private string CleanBase64String(string base64String)
        {
            base64String = base64String.Trim().Replace("\n", "").Replace("\r", "");

            base64String = new string(base64String.Where(c =>
                "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=".Contains(c)).ToArray());

            int padding = base64String.Length % 4;
            if (padding > 0)
            {
                base64String += new string('=', 4 - padding);
            }

            return base64String;
        }





