namespace IVRMUX.Controllers.com.vapstech.IssueManager
{
    [Route("api/[controller]")]
    public class ISM_EmployeeBlockReportController : Controller
    {

        public ISM_EmployeeBlockReportDelegate _objdel = new ISM_EmployeeBlockReportDelegate();

        [Route("getempblockReport")]
        public ISM_BlockEmployeeDTO getempblockReport([FromBody]ISM_BlockEmployeeDTO data)
        {
            data.MI_Id = Convert.ToInt32(HttpContext.Session.GetInt32("Session_MI_Id"));
            data.userid = Convert.ToInt32(HttpContext.Session.GetInt32("UserId"));
            data.ASMAY_Id = Convert.ToInt32(HttpContext.Session.GetInt32("ASMAY_Id"));
            return _objdel.getempblockReport(data);
        }
        [Route("getempblockNewReport")]
        public ISM_BlockEmployeeDTO getempblockNewReport([FromBody]ISM_BlockEmployeeDTO data)
        {
            data.MI_Id = Convert.ToInt32(HttpContext.Session.GetInt32("Session_MI_Id"));
            data.userid = Convert.ToInt32(HttpContext.Session.GetInt32("UserId"));
            data.ASMAY_Id = Convert.ToInt32(HttpContext.Session.GetInt32("ASMAY_Id"));
            return _objdel.getempblockNewReport(data);
        }

