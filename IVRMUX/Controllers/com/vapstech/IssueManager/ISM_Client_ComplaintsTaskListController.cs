namespace IVRMUX.Controllers.com.vapstech.IssueManager
{
    [Route("api/[controller]")]
    public class ISM_Client_ComplaintsTaskListController : Controller
    {

        public ISM_Client_ComplaintsTaskListDelegate _objdel = new ISM_Client_ComplaintsTaskListDelegate();

        [Route("getdetails")]
        public ISM_ComplaintsTaskListDTO getdetails([FromBody]ISM_ComplaintsTaskListDTO data)
        {
            data.MI_Id = Convert.ToInt32(HttpContext.Session.GetInt32("Session_MI_Id"));
            data.UserId = Convert.ToInt32(HttpContext.Session.GetInt32("UserId"));
            data.ASMAY_Id = Convert.ToInt32(HttpContext.Session.GetInt32("ASMAY_Id"));
            data.Role_flag = Convert.ToString(HttpContext.Session.GetString("Roleflag"));
            data.IVRMRT_Id = Convert.ToInt32(HttpContext.Session.GetInt32("RoleId"));
            return _objdel.getdetails(data);
        }
        [Route("gettaskdetails")]
        public ISM_ComplaintsTaskListDTO gettaskdetails([FromBody]ISM_ComplaintsTaskListDTO data)
        {
